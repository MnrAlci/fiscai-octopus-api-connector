#!/usr/bin/env python3
"""Genereert de volledige handleidingen (NL/EN) als Markdown, PDF en DOCX in docs/manuals/.

Gebruik: python3 scripts/build_manuals.py [--md-only]
PDF vraagt Chrome/Chromium (headless); DOCX vraagt python-docx; markdown en Pillow voor de HTML-stap. Doet geen Octopus-calls.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path[:0] = [str(ROOT / "scripts")]
from build_docs import tables, tool_defs  # noqa: E402
from manual_texts import MAN_EN, MAN_NL  # noqa: E402

ATTR = "Powered by FISCALCI Accounting & Tax (Askin Alci)"
BE_EN = ("Intended for Belgian bookkeepers/accountants; based on Belgian accounting and VAT rules (MAR, Belgian VAT system). "
         "Use outside Belgium: verify the local rules yourself.")
BE_NL = ("Bedoeld voor Belgische boekhouders/accountants; gebaseerd op Belgische boekhoud- en btw-regels (MAR, Belgisch btw-stelsel). "
         "Gebruik buiten België: verifieer zelf de lokale regels.")
OUT = ROOT / "docs" / "manuals"
DOCS = (("en", "FISCAi Octopus API Connector: complete manual", "manual.en.md", "FISCAi-Octopus-API-Connector-manual-EN"),
        ("nl", "FISCAi Octopus API Connector: volledige handleiding", "handleiding.nl.md", "FISCAi-Octopus-API-Connector-handleiding-NL"))


def render_md(lang: str) -> str:
    defs = tool_defs()
    tbl, n = tables(lang, defs)
    ro = sum(1 for d in defs.values() if not d["name"].startswith("octopus_schrijf_"))
    src = MAN_EN if lang == "en" else MAN_NL
    return (src.replace("{be}", BE_EN if lang == "en" else BE_NL).replace("{attr}", ATTR).replace("{n}", str(n))
            .replace("{ro}", str(ro)).replace("{tools}", tbl))


def main() -> None:
    md_only = "--md-only" in sys.argv
    OUT.mkdir(parents=True, exist_ok=True)
    logo = ROOT / "assets" / "logo-icoon-512.png"
    for lang, title, md_name, stem in DOCS:
        md = render_md(lang)
        (OUT / md_name).write_text(md, encoding="utf-8")
        if md_only:
            continue
        from manual_render import build_docx, build_pdf
        ok = build_pdf(md, title, logo, OUT / f"{stem}.pdf", lang)
        build_docx(md, title, logo, OUT / f"{stem}.docx")
        print(f"{md_name}, {stem}.docx" + (f", {stem}.pdf" if ok else " (PDF overgeslagen)"))
    (OUT / "README.md").write_text(
        "# Manuals / Handleidingen\n\n"
        "| | English | Nederlands |\n|---|---|---|\n"
        f"| Markdown | [manual.en.md](manual.en.md) | [handleiding.nl.md](handleiding.nl.md) |\n"
        f"| PDF | [{DOCS[0][3]}.pdf]({DOCS[0][3]}.pdf) | [{DOCS[1][3]}.pdf]({DOCS[1][3]}.pdf) |\n"
        f"| DOCX | [{DOCS[0][3]}.docx]({DOCS[0][3]}.docx) | [{DOCS[1][3]}.docx]({DOCS[1][3]}.docx) |\n\n"
        "Generated by `scripts/build_manuals.py` (Markdown always; PDF with Chrome/Chromium headless, DOCX with python-docx) in the minimalist "
        "FISCALCI house style: seal, FISCALCI, Accounting & Tax, colours #092B47, #016BFC, #01D0FD.\n\n" + ATTR + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
