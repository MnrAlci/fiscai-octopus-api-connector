"""Genereert docs/TOOLS.md (EN) en docs/TOOLS.nl.md uit de tooldefinities, met endpoint en daglimiet per tool.

Gebruik: python scripts/build_docs.py   (zonder Octopus-gegevens; doet geen calls)
"""
from __future__ import annotations

import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path[:0] = [str(ROOT / "server"), str(ROOT / "server" / "vendor"), str(ROOT / "scripts")]
ATTR = "Powered by FISCALCI Accounting & Tax (Askin Alci)"


def tool_defs() -> dict:
    old = os.environ.get("OCTOPUS_WRITE_ENABLED")
    os.environ["OCTOPUS_WRITE_ENABLED"] = "true"        # alleen om de schrijftools mee te documenteren
    try:
        from octopus_mcp.tools import Tools
        return {d["name"]: d for d in Tools().list()}
    finally:
        if old is None:
            os.environ.pop("OCTOPUS_WRITE_ENABLED", None)
        else:
            os.environ["OCTOPUS_WRITE_ENABLED"] = old


def endpoints_of(desc: str, lang: str = "en") -> str:
    eps = re.findall(r"((?:GET|POST|PUT) /[^\s;,)]*)(?:; daglimiet (\d+))?", desc)
    per = "/day" if lang == "en" else "/dag"
    return "<br>".join(f"`{e}`" + (f" ({n}{per})" if n else "") for e, n in eps) or ("local" if lang == "en" else "lokaal")


def tables(lang: str, defs: dict | None = None) -> tuple[str, int]:
    from doc_texts import EN, GROUPS
    defs = defs or tool_defs()
    out, n = [], 0
    for _, en, nl, names in GROUPS:
        out.append(f"### {en if lang == 'en' else nl}\n")
        out.append("| Tool | " + ("What it does | Octopus endpoint (daily limit)" if lang == "en" else "Wat het doet | Octopus-endpoint (daglimiet)") + " |")
        out.append("|---|---|---|")
        for name in names:
            d = defs[name]
            text = EN[name] if lang == "en" else re.sub(r"\s*\((?:GET|POST|PUT) /.*\)\.?$", ".", d["description"]).strip()
            out.append(f"| `{name}` | {text} | {endpoints_of(d['description'], lang)} |")
            n += 1
        out.append("")
    return "\n".join(out), n


def main() -> None:
    from doc_texts import GROUPS
    defs = tool_defs()
    names = {n for *_, ns in GROUPS for n in ns}
    missing = set(defs) - names
    if missing:
        raise SystemExit(f"Tools zonder documentatiegroep: {sorted(missing)}")
    ro = sum(1 for d in defs.values() if d["annotations"]["readOnlyHint"] and not d["name"].startswith("octopus_schrijf_"))
    en, n = tables("en", defs)
    nl, _ = tables("nl", defs)
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "TOOLS.md").write_text(
        f"# Tools\n\n{n} tools: **{ro} read-only/local** (always on) and **{n - ro} write tools** that only exist with `OCTOPUS_WRITE_ENABLED=true`.\n"
        "Daily limits come from the official Octopus REST specification (\"Maximum allowed calls per day\"); the connector refuses a call *before* "
        "sending it when the limit for today (Europe/Brussels) is reached. See `octopus_quota`.\n\n"
        "_Generated by `scripts/build_docs.py`. Dutch: [TOOLS.nl.md](TOOLS.nl.md)._\n\n" + en + "\n" + ATTR + "\n", encoding="utf-8")
    (ROOT / "docs" / "TOOLS.nl.md").write_text(
        f"# Tools\n\n{n} tools: **{ro} alleen-lezen/lokaal** (altijd aan) en **{n - ro} schrijftools** die alleen bestaan met `OCTOPUS_WRITE_ENABLED=true`.\n"
        "De daglimieten komen uit de officiële Octopus REST-specificatie (\"Maximum allowed calls per day\"); de connector weigert een call *voor* hij "
        "verstuurd wordt als de limiet van vandaag (Europe/Brussels) bereikt is. Zie `octopus_quota`.\n\n"
        "_Gegenereerd door `scripts/build_docs.py`. English: [TOOLS.md](TOOLS.md)._\n\n" + nl + "\n" + ATTR + "\n", encoding="utf-8")
    from octopus_mcp.exporting import export_schema
    sch = export_schema(None)["datasets"]
    parts = ["# Export schema\n", "Datasets written by `octopus_export_dataset` / `octopus-api-connector export` (CSV in UTF-8 with a header row, JSON with "
             "`schema` and `rijen`, xlsx, Parquet). The same columns are used in the dossier transfer. The column `administratie` holds the Octopus "
             "dossier id (shared name across FISCAi connectors). Amounts are EUR with sign `debet - credit` unless stated otherwise "
             "(verifieer actuele regel, see [OPEN-QUESTIONS.md](OPEN-QUESTIONS.md)).\n", "_Generated by `scripts/build_docs.py`._\n"]
    for ds in sorted(sch):
        parts.append(f"## `{ds}`\n\n| Column | Type | Description (NL) |\n|---|---|---|")
        parts += [f"| `{c['naam']}` | {c['type']} | {c['omschrijving']} |" for c in sch[ds]]
        parts.append("")
    (ROOT / "docs" / "EXPORT-SCHEMA.md").write_text("\n".join(parts) + "\n" + ATTR + "\n", encoding="utf-8")
    print(f"docs/TOOLS.md: {n} tools ({ro} lezen/lokaal, {n - ro} schrijven); EXPORT-SCHEMA.md: {len(sch)} datasets")


if __name__ == "__main__":
    main()
